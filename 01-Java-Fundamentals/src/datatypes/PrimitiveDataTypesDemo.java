package datatypes;

public class PrimitiveDataTypesDemo {

	
	
	public static void main (String [] args)
	
	{
		byte age = 22;
		short year = 2026;
		int salary = 500000;
		long population = 1000000000L;
		float percentage = 18.94f;
		double balance = 1232342.89;
		
		
		System.out.println("byte value "+ age );
		System.out.println("short value "+ year );
		System.out.println("int value "+ salary );
		System.out.println("population value "+ population );
		System.out.println("percentage value "+ percentage );
		System.out.println("balance value "+ balance );
	}
	
}
